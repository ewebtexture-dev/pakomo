import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import {database} from '../src/server/database.js';
fs.mkdirSync('.data',{recursive:true});
const directory=fs.mkdtempSync(path.join(process.cwd(),'.data','migration-check-'));
process.env.DATA_DIRECTORY=directory;
const legacy=new DatabaseSync(path.join(directory,'website.sqlite'));
legacy.exec(`CREATE TABLE posts(id TEXT PRIMARY KEY,slug TEXT UNIQUE NOT NULL,title TEXT NOT NULL,excerpt TEXT NOT NULL DEFAULT '',content TEXT NOT NULL DEFAULT '',category TEXT NOT NULL DEFAULT 'industry_insights',author TEXT NOT NULL DEFAULT 'PAKMOO',image_url TEXT NOT NULL DEFAULT '',image_alt TEXT NOT NULL DEFAULT '',meta_title TEXT NOT NULL DEFAULT '',meta_description TEXT NOT NULL DEFAULT '',canonical_url TEXT NOT NULL DEFAULT '',noindex INTEGER NOT NULL DEFAULT 0,status TEXT NOT NULL DEFAULT 'draft',published_at TEXT,created_at TEXT NOT NULL,updated_at TEXT NOT NULL)`);
legacy.prepare('INSERT INTO posts(id,slug,title,content,author,created_at,updated_at) VALUES(?,?,?,?,?,?,?)').run('legacy-id','existing-post','Keep this article','<p>Original article body</p>','Existing Author','2026-01-01T00:00:00Z','2026-01-01T00:00:00Z');
legacy.close();
let db=database();
const post=db.prepare('SELECT * FROM posts WHERE id=?').get('legacy-id');
assert.equal(post.content,'<p>Original article body</p>');assert.equal(post.title,'Keep this article');
assert.equal(db.prepare('SELECT name FROM authors WHERE id=?').get(post.author_id).name,'Existing Author');
assert.equal(post.focus_keyword,'');assert.equal(post.nofollow,0);
assert.throws(()=>db.prepare('DELETE FROM authors WHERE id=?').run(post.author_id),/FOREIGN KEY/);
const count=db.prepare('SELECT count(*) AS count FROM authors').get().count;
db.close();delete globalThis.__pakmooDatabase;
db=database();assert.equal(db.prepare('SELECT count(*) AS count FROM authors').get().count,count);
assert.equal(db.prepare('SELECT author_id FROM posts WHERE id=?').get('legacy-id').author_id,post.author_id);
db.close();delete globalThis.__pakmooDatabase;
for(const filename of ['website.sqlite','website.sqlite-wal','website.sqlite-shm','pre-2910-02-backup.sqlite'])fs.rmSync(path.join(directory,filename),{force:true});
fs.rmdirSync(directory);
console.log('PASS: existing article content and authors preserved; foreign keys enforced; migration is repeatable.');
